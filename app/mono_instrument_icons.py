def kind(uri, name, plugin_kind):
    value=(uri+' '+name).lower()
    if plugin_kind=='INSTRUMENT':
        return 'fm' if any(v in value for v in ('dexed','dx7','fm synth')) else 'synth'
    if any(v in value for v in ('reverb','room','hall')):return 'reverb'
    if any(v in value for v in ('delay','echo')):return 'delay'
    return 'filter' if any(v in value for v in ('filter','eq','cutoff')) else 'osc'


def paint(canvas, name, x, y):
    for yy,row in enumerate(ICONS.get(name,ICONS['synth'])):
        for xx,bit in enumerate(row):
            if bit=='1':canvas.rect(x+xx,y+yy,1,1)


def arrows(canvas, left, right, y=34):
    # Filled arrowheads, no font glyphs / replacement characters.
    for step in range(4):
        if left:canvas.rect(3+step,y-step,1,step*2+1)
        if right:canvas.rect(251-step,y-step,1,step*2+1)


def overview(app):
    """Detached first-page detail, including the implicit sampler source."""
    offset=int(app.sampler_slot_present())
    items=app.plugin_target().get('plugins',[])
    current=0 if app.page in ('SAMPLER','AUDIO LOOP') else app.plugin_slot+offset
    count=len(items)+offset
    if not 0<=current<count:return None
    source=app.page in ('SAMPLER','AUDIO LOOP')
    plugin=None if source else app.plugin_selected()
    meta=(app.plugin_metadata(plugin['uri']) or {}) if plugin else {}
    name=('AUDIO' if app.page=='AUDIO LOOP' else 'SAMPLER') if source else meta.get('name',plugin['uri'])
    return dict(name=name,icon=None if source else kind(plugin['uri'],name,plugin.get('kind',meta.get('kind','EFFECT'))),
                selected=current,count=count,left=current>0,right=current+1<count,
                bypass=bool(plugin and plugin.get('bypass',False)),source=source,
                role='INSTRUMENT' if plugin and plugin.get('kind',meta.get('kind'))=='INSTRUMENT' else 'EFFECT')


def channel_art(app):
    """Source illustration for OUTPUT, including linked group instruments."""
    target=app.plugin_target();seen=set();effect=None
    if target.get('sample') or target.get('zones'):return None
    for _ in range(4):
        if id(target) in seen:break
        seen.add(id(target))
        for plugin in target.get('plugins',[]):
            uri=plugin.get('uri','');meta=app.plugin_metadata(uri) or {}
            if plugin.get('kind',meta.get('kind'))=='INSTRUMENT':
                return kind(uri,meta.get('name',uri),'INSTRUMENT')
            if effect is None:effect=kind(uri,meta.get('name',uri),'EFFECT')
        route=target.get('routing',{}).get('midi_target','NONE')
        if not isinstance(route,str) or not route.startswith('GROUP '):break
        try:target=app.project['groups'][int(route[6:])] if int(route[6:])>=0 else None
        except (ValueError,IndexError,TypeError):break
        if target is None:break
    return effect or ('synth' if app.plugin_target().get('source')=='MIDI' else None)


def paint_channel(canvas, name):
    """Wide native-pixel panel, within the existing 20-row content area."""
    x,y=4,25
    canvas.rect(x,y,104,20,fill=False)
    if name in ('synth','fm'):
        # Front panel: waveform / operator display and parameter knobs.
        paint(canvas,'fm' if name=='fm' else 'osc',x+3,y)
        for cx in (42,54,66,78,90):
            canvas.rect(x+cx,y+3,5,5,fill=False)
            canvas.rect(x+cx+2,y+2,1,3)
        canvas.rect(x+39,y+11,60,7,fill=False)
        for cx in range(45,98,6):canvas.rect(x+cx,y+12,1,5)
        for cx in (44,50,62,68,74,86,92):canvas.rect(x+cx,y+11,2,3)
    else:
        paint(canvas,name,x+5,y)
        for cx,level in ((49,9),(65,4),(81,11)):
            canvas.rect(x+cx,y+3,1,14)
            canvas.rect(x+cx-3,y+level,7,3)
        canvas.rect(x+94,y+14,3,3)


