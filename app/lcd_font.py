# Names and plug-in metadata use ordinary punctuation as well as letters.
# Cover every printable ASCII character instead of drawing a question mark.
_PUNCTUATION={
    '!':'1 1 1 0 1', '"':'101 101 000 000 000',
    '$':'0111 1100 0110 0011 1110', "'":'1 1 0 0 0',
    '(':'01 10 10 10 01', ')':'10 01 01 01 10',
    ',':'00 00 00 01 10', ';':'00 01 00 01 10',
    '=':'000 111 000 111 000', '@':'01110 10011 10111 10000 01110',
    '\\':'10000 01000 00100 00010 00001', '^':'010 101 000 000 000',
    '`':'10 01 00 00 00', '{':'011 010 110 010 011',
    '|':'1 1 1 1 1', '}':'110 010 011 010 110',
    '~':'0000 0101 1010 0000 0000',
}
for face in FONTS.values():
    for character,drawing in _PUNCTUATION.items():
        rows=drawing.split()
        face[character]=rows if len(face['A'])==5 else [rows[i] for i in (0,1,1,2,3,3,4)]
    for character in 'abcdefghijklmnopqrstuvwxyz':face.setdefault(character,face[character.upper()])
