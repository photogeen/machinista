"""Generate a compact 64-phase Blackman-windowed interpolation kernel."""
from pathlib import Path
import math
rows=[]
for phase in range(65):
 fraction=phase/64;values=[]
 for tap in range(16):
  x=tap-7-fraction
  window=.42+.5*math.cos(math.pi*x/8)+.08*math.cos(math.pi*x/4) if abs(x)<8 else 0
  values.append((math.sin(math.pi*x)/(math.pi*x) if abs(x)>1e-12 else 1)*window)
 total=sum(values);rows.append(','.join(f'{v/total:.10f}f' for v in values))
path=Path(__file__).resolve().parents[1]/'src/audio/live_pitch_kernel.hpp'
path.write_text('#pragma once\n// Generated by tools/generate_pitch_kernel.py; original DSP coefficients.\ninline constexpr float live_pitch_kernel[65][16]={\n'+''.join('{'+row+'},\n' for row in rows)+'};\n')
